import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { benchmarkPopulationGaps, humanReviewVerdict } from "./contracts.mjs";
const briefs=JSON.parse(readFileSync(new URL("./briefs.json",import.meta.url)));
assert.deepEqual(benchmarkPopulationGaps(briefs),[]);
assert.match(benchmarkPopulationGaps([]).join(" "),/population 0\/24/);
assert.match(benchmarkPopulationGaps(briefs.filter(b=>b.category!=="datagrid")).join(" "),/datagrid 0\/6/);
const review=JSON.parse(readFileSync(new URL("./human-review.json",import.meta.url)));
assert.equal(review.status,"pending-human-review");assert.equal(review.reviews.length,0);
assert.equal(review.threshold.minimumCurrentPreferenceRate,.75);
const hundred=Array.from({length:100},(_,i)=>({id:`pair-${i}`})), key=Object.fromEntries(hundred.map(b=>[b.id,{A:"current",B:"baseline"}]));
const choices=n=>hundred.map((b,i)=>({id:b.id,choice:i<n?"A":"B"}));
assert.equal(humanReviewVerdict({briefs:hundred,key,choices:choices(74)}).pass,false,"74% must fail");
assert.equal(humanReviewVerdict({briefs:hundred,key,choices:choices(75)}).pass,true,"75% must pass");
const key24=Object.fromEntries(briefs.map(b=>[b.id,{A:"current",B:"baseline"}]));
const choices24=n=>briefs.map((b,i)=>({id:b.id,choice:i<n?"A":"B"}));
assert.equal(humanReviewVerdict({briefs,key:key24,choices:choices24(17)}).pass,false);
assert.equal(humanReviewVerdict({briefs,key:key24,choices:choices24(18)}).pass,true);
assert.match(humanReviewVerdict({briefs,key:key24,choices:[...choices24(24),choices24(24)[0]]}).gaps.join(" "),/duplicate pair/);
assert.match(humanReviewVerdict({briefs,key:key24,choices:choices24(24).slice(1)}).gaps.join(" "),/missing pair/);
console.log("benchmark contract PASS: population bites; 74% fails/75% passes; 24 pair identity + denominator enforced; human gate pending");
